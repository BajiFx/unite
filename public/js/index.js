async function handleCustomerRegister() {
  const name = document.getElementById('regCustomerName').value.trim();
  const phone = document.getElementById('regCustomerPhone').value.trim();
  const email = document.getElementById('regCustomerEmail').value.trim();
  const password = document.getElementById('regCustomerPassword').value;
  const confirm = document.getElementById('regCustomerConfirm').value;
  const status = document.getElementById('customerRegisterStatus');
  if (!status) return;

  status.textContent = '';
  status.className = 'auth-status';
  status.style.color = '';

  if (!name || !phone || !password || !confirm) {
    status.textContent = '❌ Please fill in your name, phone number, and password.';
    status.className = 'auth-status error';
    return;
  }

  const phoneRegex = /^[0-9]{10,15}$/;
  const cleanPhone = phone.replace(/[^0-9]/g, '');
  if (!phoneRegex.test(cleanPhone)) {
    status.textContent = '❌ Please enter a valid phone number (10-15 digits).';
    status.className = 'auth-status error';
    return;
  }

  if (password.length < 6) {
    status.textContent = '❌ Password must be at least 6 characters.';
    status.className = 'auth-status error';
    return;
  }
  if (password !== confirm) {
    status.textContent = '❌ Passwords do not match.';
    status.className = 'auth-status error';
    return;
  }

  if (email) {
    const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    if (!emailRegex.test(email)) {
      status.textContent = '❌ Please enter a valid email address, or leave it blank.';
      status.className = 'auth-status error';
      return;
    }
  }

  status.textContent = '⏳ Creating account...';
  status.className = 'auth-status';
  status.style.color = '#2563eb';

  try {
    const res = await fetch('/api/auth/customer/register', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        name,
        phone: cleanPhone,
        password,
        email: email || null
      })
    });
    const data = await res.json();

    if (res.ok && data.success) {
      status.textContent = '✅ Account created!';
      status.className = 'auth-status success';

      window.customerToken = 'cookie-auth';
      localStorage.setItem('currentUser', JSON.stringify(data.customer));
      currentUser = data.customer;

      const nameEl = document.getElementById('regCustomerName');
      const phoneEl = document.getElementById('regCustomerPhone');
      const emailEl = document.getElementById('regCustomerEmail');
      const pwdEl = document.getElementById('regCustomerPassword');
      const confirmEl = document.getElementById('regCustomerConfirm');
      if (nameEl) nameEl.value = '';
      if (phoneEl) phoneEl.value = '';
      if (emailEl) emailEl.value = '';
      if (pwdEl) pwdEl.value = '';
      if (confirmEl) confirmEl.value = '';

      closeAuthModal();

      const generatedUsername = data.customer && data.customer.username
        ? data.customer.username
        : '';

      if (generatedUsername) {
        showToast(
          `✅ Welcome, ${data.customer.name || 'User'}! Your username is "${generatedUsername}".`,
          'success'
        );
      } else {
        showToast(`✅ Welcome, ${data.customer?.name || 'User'}!`, 'success');
      }

      checkAuthState();
    } else {
      status.textContent = '❌ ' + (data.error || 'Registration failed');
      status.className = 'auth-status error';
    }
  } catch (err) {
    status.textContent = '❌ Network error. Please try again.';
    status.className = 'auth-status error';
    console.error('Register error:', err);
  }
}

