function getAdSlotDurationMsForAd(ad) {
  if (ad && ad.media_type === 'video') return AD_VIDEO_SLOT_MS;
  return AD_IMAGE_SLOT_MS;
}

/**
 * Display the slide at `index` and arm the next transition.
 *
 * This is the single entry point for the rotation. Every path
 * that changes the current slide — the natural timer, the
 * prev/next buttons, the dots, and the initial render — calls
 * this function. That guarantees the timer chain is never left
 * with two pending timers, and the round-robin order is always
 * respected.
 */
function showAdAtIndex(index) {
  if (!Array.isArray(adsList) || adsList.length === 0) return;

  const total = adsList.length;
  const next = ((index % total) + total) % total;

  // Cancel any pending transition before scheduling the next one.
  if (adsTransitionTimer) {
    clearTimeout(adsTransitionTimer);
    adsTransitionTimer = null;
  }

  adsCurrentIndex = next;
  adsSlideStartedAt = Date.now();
  adsSlideDuration = getAdSlotDurationMsForAd(adsList[next]);

  adsImpressionFiredFor.add(next);
  updateAdsActiveSlide();
  fireAdImpression(next);
  restartAdsProgressLoop();

  // Arm the next transition. If the slider is paused, the timer
  // is not armed; unpausing calls `resumeAdChain()` which arms
  // it again from the current slide.
  if (!adsIsPaused) {
    adsTransitionTimer = setTimeout(() => {
      adsTransitionTimer = null;
      showAdAtIndex(adsCurrentIndex + 1);
    }, adsSlideDuration);
  }
}

/**
 * Advance one slide. Used by the prev/next buttons and the dots.
 * Kept under the old name so existing inline handlers keep
 * working.
 */
function jumpAdClockToIndex(index) {
  if (!Array.isArray(adsList) || adsList.length === 0) return;
  showAdAtIndex(index);
}

/**
 * Called when the user stops hovering / focusing the slider.
 * Re-arms the timer for the remainder of the current slide so
 * the rotation does not jump or stall.
 */
function resumeAdChain() {
  if (!Array.isArray(adsList) || adsList.length === 0) return;
  if (adsIsPaused) return;

  if (adsTransitionTimer) {
    clearTimeout(adsTransitionTimer);
    adsTransitionTimer = null;
  }

  const elapsed = Date.now() - adsSlideStartedAt;
  const remaining = Math.max(0, adsSlideDuration - elapsed);

  adsTransitionTimer = setTimeout(() => {
    adsTransitionTimer = null;
    showAdAtIndex(adsCurrentIndex + 1);
  }, remaining);
}

/**
 * Stop the rotation entirely. Safe to call multiple times.
 */
function stopAdClock() {
  if (adsTransitionTimer) { clearTimeout(adsTransitionTimer); adsTransitionTimer = null; }
  if (adsProgressTimer) { clearInterval(adsProgressTimer); adsProgressTimer = null; }
}

/**
 * Kept for backward compatibility with the old name. The
 * rotation now starts as soon as `showAdAtIndex(0)` is called
 * from `renderAdsSlider`, so this function is a no-op unless the
 * caller explicitly wants to restart the chain from index 0.
 */
function startAdClock() {
  if (!Array.isArray(adsList) || adsList.length <= 1) return;
  showAdAtIndex(0);
}

/**
 * Restart the progress bar for the current slide. The bar runs
 * off `adsSlideStartedAt` and `adsSlideDuration`, not off the
 * wall clock, so it always matches what the user sees.
 */
function restartAdsProgressLoop() {
  if (adsProgressTimer) clearInterval(adsProgressTimer);

  const tick = () => {
    const duration = adsSlideDuration;
    if (!Number.isFinite(duration) || duration <= 0) return;
    const elapsed = Date.now() - adsSlideStartedAt;
    const ratio = Math.max(0, Math.min(1, elapsed / duration));
    updateAdsProgressBar(ratio);
  };

  tick();
  adsProgressTimer = setInterval(tick, 100);
}

function updateAdsProgressBar(ratio) {
  const bar = document.getElementById('adsProgress');
  if (!bar) return;
  const pct = Math.max(0, Math.min(1, ratio)) * 100;
  bar.style.setProperty('--ads-progress', `${pct}%`);
  bar.style.width = `${pct}%`;
}

async function loadAds() {
  const section = document.getElementById('adsSliderSection');
  const slider = document.getElementById('adsSlider');
  const dots = document.getElementById('adsDots');
  if (!section || !slider || !dots) return;

  try {
    const res = await fetch('/api/businesses/ads', {
      credentials: 'same-origin',
      cache: 'no-store'
    });
    if (!res.ok) throw new Error(`Ads request failed (${res.status})`);

    const data = await res.json();
    adsList = Array.isArray(data.ads) ? data.ads.filter(ad => ad && ad.media_url) : [];

    updateAdRotationMetaFromResponse(data);

    if (adsList.length === 0) {
      section.hidden = true;
      stopAdClock();
      return;
    }

    renderAdsSlider();
    section.hidden = false;
    bindAdsSliderOnce();
    // Kick off the rotation from index 0.
    showAdAtIndex(0);
  } catch (err) {
    console.warn('Ads slider skipped:', err.message);
    section.hidden = true;
    stopAdClock();
  }
}

function renderAdsSlider() {
  const mediaFrame = document.getElementById('adsMediaFrame');
  const dots = document.getElementById('adsDots');
  if (!mediaFrame || !dots) return;

  mediaFrame.querySelectorAll('.ads-slide').forEach(node => node.remove());

  mediaFrame.insertAdjacentHTML(
    'afterbegin',
    adsList.map((ad, index) => renderAdSlide(ad, index)).join('')
  );

  dots.innerHTML = adsList.map((ad, index) => {
    const label = ad.title ? escapeAdsText(ad.title) : `Ad ${index + 1}`;
    return `
      <button
        type="button"
        class="ads-dot${index === 0 ? ' is-active' : ''}"
        data-ad-index="${index}"
        role="tab"
        aria-label="${label}"
        aria-selected="${index === 0 ? 'true' : 'false'}"
      ></button>
    `;
  }).join('');

  adsImpressionFiredFor = new Set();
  adsCurrentIndex = 0;
  adsImpressionFiredFor.add(0);
  updateAdsActiveSlide();
  fireAdImpression(0);

  dots.querySelectorAll('.ads-dot').forEach(dot => {
    dot.addEventListener('click', () => {
      const idx = parseInt(dot.dataset.adIndex, 10);
      if (!Number.isInteger(idx)) return;
      jumpAdClockToIndex(idx);
    });
  });
}

function pickAdBackdrop(ad) {
  const id = Number(ad && ad.id) || 0;
  return AD_BACKDROP_PALETTE[Math.abs(id) % AD_BACKDROP_PALETTE.length];
}

function renderAdSlide(ad, index) {
  const isVideo = ad.media_type === 'video';
  const title = ad.title ? `<h3 class="ads-title">${escapeAdsText(ad.title)}</h3>` : '';
  const description = ad.description ? `<p class="ads-description">${escapeAdsText(ad.description)}</p>` : '';
  const businessName = ad.business_name ? `<span class="ads-business">${escapeAdsText(ad.business_name)}</span>` : '';

  const mediaSrc = escapeAdsAttr(ad.media_url);
  const mediaAlt = escapeAdsAttr(ad.title || ad.business_name || 'Sponsored');
  const [bgA, bgB] = pickAdBackdrop(ad);

  // Video: no `muted` attribute. Audio will play when the browser
  // allows it (see updateAdsActiveSlide for the fallback logic).
  // preload="auto" buffers the whole file so sound starts as soon
  // as the slide becomes active.
  const media = isVideo
    ? `<video class="ads-media" src="${mediaSrc}" playsinline preload="auto"></video>`
    : `
        <div class="ads-media-bg" aria-hidden="true" style="--ad-bg-a:${bgA}; --ad-bg-b:${bgB};"></div>
        <img class="ads-media" src="${mediaSrc}" alt="${mediaAlt}" loading="lazy">
      `;

  const slideClass = `ads-slide${index === adsCurrentIndex ? ' is-active' : ''} ${isVideo ? 'is-video' : 'is-image'}`;

  return `
    <div class="${slideClass}" data-ad-index="${index}" data-ad-id="${ad.id}">
      <div class="ads-media-wrap">
        ${media}
        <div class="ads-overlay"></div>
        <div class="ads-caption">
          ${businessName}
          ${title}
          ${description}
        </div>
      </div>
    </div>
  `;
}

function bindAdsSliderOnce() {
  if (adsSliderBound) return;
  adsSliderBound = true;

  const slider = document.getElementById('adsSlider');
  const prevBtn = document.getElementById('adsPrevBtn');
  const nextBtn = document.getElementById('adsNextBtn');

  if (prevBtn) {
    prevBtn.addEventListener('click', (event) => {
      event.stopPropagation();
      jumpAdClockToIndex(adsCurrentIndex - 1);
    });
  }
  if (nextBtn) {
    nextBtn.addEventListener('click', (event) => {
      event.stopPropagation();
      jumpAdClockToIndex(adsCurrentIndex + 1);
    });
  }

  if (slider) {
    slider.addEventListener('mouseenter', () => {
      adsIsPaused = true;
      if (adsTransitionTimer) { clearTimeout(adsTransitionTimer); adsTransitionTimer = null; }
    });
    slider.addEventListener('mouseleave', () => {
      adsIsPaused = false;
      resumeAdChain();
    });
    slider.addEventListener('focusin', () => {
      adsIsPaused = true;
      if (adsTransitionTimer) { clearTimeout(adsTransitionTimer); adsTransitionTimer = null; }
    });
    slider.addEventListener('focusout', () => {
      adsIsPaused = false;
      resumeAdChain();
    });

    slider.addEventListener('click', (event) => {
      if (event.target.closest('.ads-nav')) return;
      const slide = event.target.closest('.ads-slide');
      if (!slide) return;
      const idx = parseInt(slide.dataset.adIndex, 10);
      if (Number.isInteger(idx)) handleAdClick(idx);
    });

    slider.addEventListener('keydown', (event) => {
      if (event.key === 'ArrowLeft') {
        event.preventDefault();
        jumpAdClockToIndex(adsCurrentIndex - 1);
      } else if (event.key === 'ArrowRight') {
        event.preventDefault();
        jumpAdClockToIndex(adsCurrentIndex + 1);
      }
    });
  }
}

function updateAdsActiveSlide() {
  const mediaFrame = document.getElementById('adsMediaFrame');
  if (mediaFrame) {
    mediaFrame.querySelectorAll('.ads-slide').forEach(slide => {
      const idx = parseInt(slide.dataset.adIndex, 10);
      slide.classList.toggle('is-active', idx === adsCurrentIndex);
    });

    mediaFrame.querySelectorAll('.ads-slide').forEach(slide => {
      const idx = parseInt(slide.dataset.adIndex, 10);
      const video = slide.querySelector('video');
      if (!video) return;

      if (idx === adsCurrentIndex) {
        // This is the active video.
        try { video.currentTime = 0; } catch (e) {}

        // Try to play WITH SOUND first. If the browser blocks
        // autoplay-with-audio (no user gesture yet, or a strict
        // autoplay policy), fall back to muted playback so the
        // video is at least visibly running. We do NOT set the
        // muted attribute permanently — only the .muted property
        // for this one attempt — so the next slide transition
        // will try with sound again.
        video.muted = false;
        video.volume = 1;

        const playAttempt = video.play();
        if (playAttempt && typeof playAttempt.catch === 'function') {
          playAttempt.catch(() => {
            // Browser blocked sound. Retry once, muted, so the
            // frame is not frozen. Sound stays off for THIS slide
            // only; the next transition tries with sound again.
            try {
              video.muted = true;
              video.play().catch(() => {});
            } catch (e) {
              // Give up silently — the poster / first frame is fine.
            }
          });
        }
      } else {
        // Not the active slide. Pause and mute so a background
        // video does not emit sound if it was somehow still
        // playing.
        try { video.pause(); } catch (e) {}
        try { video.muted = true; } catch (e) {}
      }
    });
  }

  const dots = document.getElementById('adsDots');
  if (dots) {
    dots.querySelectorAll('.ads-dot').forEach(dot => {
      const idx = parseInt(dot.dataset.adIndex, 10);
      const active = idx === adsCurrentIndex;
      dot.classList.toggle('is-active', active);
      dot.setAttribute('aria-selected', active ? 'true' : 'false');
    });
  }
}

function fireAdImpression(index) {
  if (!Number.isInteger(index)) return;
  if (adsImpressionFiredFor.has(index)) return;
  adsImpressionFiredFor.add(index);

  const ad = adsList[index];
  if (!ad || !ad.id) return;

  try {
    fetch(`/api/businesses/ads/${encodeURIComponent(ad.id)}/view`, {
      method: 'POST',
      credentials: 'same-origin',
      keepalive: true
    }).catch(() => {});
  } catch (err) {
    // Non-fatal.
  }
}

async function handleAdClick(index) {
  if (!Number.isInteger(index)) return;
  const ad = adsList[index];
  if (!ad || !ad.id) return;

  let target = null;
  try {
    const res = await fetch(`/api/businesses/ads/${encodeURIComponent(ad.id)}/click`, {
      method: 'POST',
      credentials: 'same-origin',
      keepalive: true
    });
    if (res.ok) {
      const data = await res.json();
      if (data && data.ad) target = data.ad;
    }
  } catch (err) {
    // Non-fatal.
  }

  const linkType = (target && target.link_type) || ad.link_type || 'profile';
  const linkTargetId = (target && target.link_target_id) || ad.link_target_id || null;
  const businessSlug = (target && target.business_slug) || ad.business_slug || null;

  if (linkType === 'product' && linkTargetId) {
    const slugParam = businessSlug ? `&business=${encodeURIComponent(businessSlug)}` : '';
    window.location.href = `/product-detail.html?id=${encodeURIComponent(linkTargetId)}${slugParam}`;
    return;
  }

  if (businessSlug) {
    window.location.href = `/business/${encodeURIComponent(businessSlug)}`;
    return;
  }

  console.warn('Ad has no navigable target:', ad);
}

